// Get the relevant law for a given situation
export const getLawForSituation = (situation: string): { lawNumber: number; law: typeof NAPOLEON_HILL_17_LAWS[1] } => {
  const situationLower = situation.toLowerCase();
  
  if (situationLower.includes("goal") || situationLower.includes("purpose") || situationLower.includes("aim")) {
    return { lawNumber: 1, law: NAPOLEON_HILL_17_LAWS[1] };
  }
  if (situationLower.includes("doubt") || situationLower.includes("fear") || situationLower.includes("confidence")) {
    return { lawNumber: 2, law: NAPOLEON_HILL_17_LAWS[2] };
  }
  if (situationLower.includes("money") || situationLower.includes("resource") || situationLower.includes("energy")) {
    return { lawNumber: 3, law: NAPOLEON_HILL_17_LAWS[3] };
  }
  if (situationLower.includes("wait") || situationLower.includes("start") || situationLower.includes("lead")) {
    return { lawNumber: 4, law: NAPOLEON_HILL_17_LAWS[4] };
  }
  if (situationLower.includes("vision") || situationLower.includes("imagine") || situationLower.includes("creative")) {
    return { lawNumber: 5, law: NAPOLEON_HILL_17_LAWS[5] };
  }
  if (situationLower.includes("energy") || situationLower.includes("motivation") || situationLower.includes("enthusiasm")) {
    return { lawNumber: 6, law: NAPOLEON_HILL_17_LAWS[6] };
  }
  if (situationLower.includes("angry") || situationLower.includes("react") || situationLower.includes("control") || situationLower.includes("emotion")) {
    return { lawNumber: 7, law: NAPOLEON_HILL_17_LAWS[7] };
  }
  if (situationLower.includes("extra") || situationLower.includes("more") || situationLower.includes("service")) {
    return { lawNumber: 8, law: NAPOLEON_HILL_17_LAWS[8] };
  }
  if (situationLower.includes("personality") || situationLower.includes("charm") || situationLower.includes("likeable")) {
    return { lawNumber: 9, law: NAPOLEON_HILL_17_LAWS[9] };
  }
  if (situationLower.includes("think") || situationLower.includes("fact") || situationLower.includes("analyze")) {
    return { lawNumber: 10, law: NAPOLEON_HILL_17_LAWS[10] };
  }
  if (situationLower.includes("focus") || situationLower.includes("distract") || situationLower.includes("concentrate")) {
    return { lawNumber: 11, law: NAPOLEON_HILL_17_LAWS[11] };
  }
  if (situationLower.includes("team") || situationLower.includes("cooperat") || situationLower.includes("together")) {
    return { lawNumber: 12, law: NAPOLEON_HILL_17_LAWS[12] };
  }
  if (situationLower.includes("fail") || situationLower.includes("mistake") || situationLower.includes("setback")) {
    return { lawNumber: 13, law: NAPOLEON_HILL_17_LAWS[13] };
  }
  if (situationLower.includes("different") || situationLower.includes("understand") || situationLower.includes("tolera")) {
    return { lawNumber: 14, law: NAPOLEON_HILL_17_LAWS[14] };
  }
  if (situationLower.includes("treat") || situationLower.includes("fair") || situationLower.includes("golden")) {
    return { lawNumber: 15, law: NAPOLEON_HILL_17_LAWS[15] };
  }
  if (situationLower.includes("mentor") || situationLower.includes("ally") || situationLower.includes("mastermind")) {
    return { lawNumber: 16, law: NAPOLEON_HILL_17_LAWS[16] };
  }
  if (situationLower.includes("habit") || situationLower.includes("pattern") || situationLower.includes("routine")) {
    return { lawNumber: 17, law: NAPOLEON_HILL_17_LAWS[17] };
  }
  
  // Default to Self-Control (most universally applicable)
  return { lawNumber: 7, law: NAPOLEON_HILL_17_LAWS[7] };
};

